export function getSpecActionLabels(locale: ResolvedUiLocale): SpecPanelExtraLabels {
  return ACTION_LABELS[locale] ?? ACTION_LABELS.en;
}

export function getDeltaKindLabel(kind: SpecDeltaKind, actions: SpecPanelExtraLabels): string {
  if (kind === 'added') return actions.deltaAdded;
  if (kind === 'removed') return actions.deltaRemoved;
  return actions.deltaModified;
}

export function getAnnotationKindLabel(
  kind: SpecAnnotationKind,
  actions: SpecPanelExtraLabels,
): string {
  if (kind === 'strike') return actions.kindStrike;
  if (kind === 'replace') return actions.kindReplace;
  return actions.kindComment;
}
